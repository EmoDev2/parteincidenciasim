// Catmull-Rom centrípeta: curva suave que pasa por los puntos sin hacer rizos raros
function spline(P, n = 7) {
  if (P.length < 3) return P.map(p => ({ x: p[0], y: p[1] }));
  const out = [], ext = [[2 * P[0][0] - P[1][0], 2 * P[0][1] - P[1][1]]].concat(P, [[2 * P[P.length - 1][0] - P[P.length - 2][0], 2 * P[P.length - 1][1] - P[P.length - 2][1]]]);
  for (let i = 0; i < ext.length - 3; i++) {
    const p0 = ext[i], p1 = ext[i + 1], p2 = ext[i + 2], p3 = ext[i + 3], d = (a, b) => Math.max(0.01, Math.pow((b[0] - a[0]) ** 2 + (b[1] - a[1]) ** 2, 0.25));
    const t1 = d(p0, p1), t2 = t1 + d(p1, p2), t3 = t2 + d(p2, p3), mix = (a, b, ta, tb, t) => [(a[0] * (tb - t) + b[0] * (t - ta)) / (tb - ta), (a[1] * (tb - t) + b[1] * (t - ta)) / (tb - ta)];
    for (let k = 0; k < n; k++) { const t = t1 + (t2 - t1) * k / n, a1 = mix(p0, p1, 0, t1, t), a2 = mix(p1, p2, t1, t2, t), a3 = mix(p2, p3, t2, t3, t), b1 = mix(a1, a2, 0, t2, t), b2 = mix(a2, a3, t1, t3, t), c = mix(b1, b2, t1, t2, t); out.push({ x: c[0], y: c[1] }); }
  }
  out.push({ x: P[P.length - 1][0], y: P[P.length - 1][1] });
  return out;
}
function genSignature(rng, fullName) {
  const clean = s => (s || "").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^A-Za-z]/g, "");
  const words = (fullName || "Marta Lopez").split(" ").map(clean).filter(Boolean), first = words[0] || "Ana", ape = words[1] || first;
  const style = rng(), slant = 0.18 + rng() * 0.3, sx = 0.75 + rng() * 0.35, low = 0.7 + rng() * 0.35, rise = -0.01 + rng() * 0.09, jit = 0.25 + rng() * 0.45;
  // qué se escribe: «M. García», «García» o «Marta G.»
  const caps = style < 0.45 ? [first[0], ape[0]] : style < 0.8 ? [ape[0]] : [first[0]];
  const bodyWord = (style < 0.8 ? ape : first).slice(1).toLowerCase(), readable = 2 + Math.floor(rng() * 4);
  const raw = []; let x = 0;
  const J = (px, py) => [px + (rng() - 0.5) * jit * 2, py + (rng() - 0.5) * jit * 2];
  caps.forEach((ch, ci) => {
    const def = CAPS[ch.toUpperCase()] || CAPS.M, k = ci === 0 ? 1 + rng() * 0.18 : 0.85 + rng() * 0.15;
    def.forEach(st => raw.push(st.map(([a, b]) => J(x + a * k, b * k))));
    x += (ci < caps.length - 1 ? 14 + rng() * 4 : 13) * k;
    if (ci === 0 && caps.length > 1 && rng() < 0.55) { raw.push([[x - 1, 0.2], [x - 0.4, 0.8]]); x += 3; }
  });
  // cuerpo en cursiva ligada; las últimas letras degeneran en un trazo rápido, como una firma de verdad
  let run = [[x - 1.5, 2]]; const extras = [];
  const letters = bodyWord.slice(0, readable);
  for (let i = 0; i < letters.length; i++) {
    const ch = letters[i], g = LOW[ch]; if (!g) continue; const shrink = 1 - i * 0.045;
    for (const [a, b] of g) run.push(J(x + a * shrink, b * (b > 11 || b < -1 ? 0.92 : low) * shrink));
    if (ch === "i" || ch === "j") extras.push([[x + 4.2, 14], [x + 4.8, 14.8]]);
    if (ch === "t") extras.push([[x + 0.5, 11.5], [x + 5, 13], [x + 10, 13.8]]);
    if (ch === "x") extras.push([[x + 2, 0], [x + 9, 10]]);
    x += LW[ch] * shrink;
  }
  const left = Math.max(2, bodyWord.length - readable + 1); let amp = 4.5 * low;
  for (let i = 0; i < Math.min(5, left); i++) { run.push(J(x + 1.5, amp), J(x + 3, amp * 0.9), J(x + 3.8, 0.6)); x += 4.5; amp *= 0.78; }
  run.push([x + 4, 2.5]); raw.push(run); extras.forEach(e => raw.push(e));
  // rúbrica
  const f = rng(), end = x + 4;
  if (f < 0.38) raw.push([[end, 2.5], [end + 6, 4 + rng() * 3], [end - 2, -3], [end * 0.55, -6 - rng() * 3], [end * 0.1, -7 - rng() * 3], [-3 - rng() * 4, -5]]); // subrayado de vuelta
  else if (f < 0.62) raw.push([[-3, -5 - rng() * 3], [end * 0.35, -4], [end * 0.7, -4.5 - rng() * 2], [end + 12, -1 + rng() * 5]]); // línea inferior
  else if (f < 0.82) raw.push([[end, 2.5], [end + 8, 10], [end + 2, 19], [end * 0.45, 20 + rng() * 5], [-4, 12], [-5, 0], [end * 0.3, -8], [end + 6, -5]]); // óvalo envolvente
  else raw.push([[end, 2.5], [end + 7, 3], [end + 13 + rng() * 8, 7 + rng() * 8]]); // cola ascendente
  if (rng() < 0.35) raw.push([[end + 9, 0], [end + 9.8, 0.6]]);
  // inclinación, subida y paso a coordenadas de pantalla (y hacia abajo)
  const K = 2.1;
  return raw.map(st => spline(st).map(p => ({ x: (p.x * sx + p.y * slant) * K, y: -(p.y + p.x * rise) * K })));
}
// trazo con presión: más grueso al bajar la pluma, fino al subir
function inkLine(pts, w, color) {
  if (pts.length < 2) { penLine(pts, w, color); return; }
  ctx.strokeStyle = color; ctx.lineCap = "round"; ctx.lineJoin = "round"; let lw = w;
  for (let i = 1; i < pts.length; i++) {
    const a = pts[i - 1], b = pts[i], dx = b.x - a.x, dy = b.y - a.y, len = Math.hypot(dx, dy) || 1;
    lw += (w * (0.62 + 0.75 * Math.max(0, dy / len)) - lw) * 0.35;
    ctx.lineWidth = lw; ctx.beginPath(); ctx.moveTo(a.x, a.y); ctx.lineTo(b.x, b.y); ctx.stroke();
  }
}
